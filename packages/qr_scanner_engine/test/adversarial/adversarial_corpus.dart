    required this.category,
    required this.expectedThreatLevel,
    required this.expectedFindingCode,
    required this.expectedActionAllowed,
    required this.minScore,
    required this.maxScore,
  });
}

/// Helper to generate authentic and tampered TrustQR vectors.
class TrustQrVectorFactory {
  static final Uint8List institutionalSeed = Uint8List.fromList(List.generate(32, (i) => (i * 31 + 7) % 256));
  static final CryptoKeyPair institutionalKeyPair = Ed25519Engine.generateKeyPairFromSeed(
    institutionalSeed,
    keyId: 'trustqr-gov-registry-01',
  );

  static String createAuthenticEnvelope() {
    final envelope = TrustQrEnvelope.sign(
      issuer: 'org.health.cert',
      payload: 'https://health.gov/credentials/verify?id=998822',
      privateKey: institutionalKeyPair.privateKey,
    );
    return envelope.toUriString();
  }

  static String createTamperedPayloadEnvelope() {
    final valid = createAuthenticEnvelope();
    final uri = Uri.parse(valid);
    final params = Map<String, String>.from(uri.queryParameters);
    params['payload'] = base64UrlEncode(utf8.encode('https://malicious-phishing.org/steal'));
    return uri.replace(queryParameters: params).toString();
  }

  static String createTamperedSignatureEnvelope() {
    final valid = createAuthenticEnvelope();
    final uri = Uri.parse(valid);
    final params = Map<String, String>.from(uri.queryParameters);
    final sigBytes = base64Url.decode(base64.normalize(params['sig']!));
    sigBytes[0] ^= 0xFF; // Flip byte
    params['sig'] = base64UrlEncode(sigBytes);
    return uri.replace(queryParameters: params).toString();
  }

  static String createTamperedIssuerEnvelope() {
    final valid = createAuthenticEnvelope();
    final uri = Uri.parse(valid);
    final params = Map<String, String>.from(uri.queryParameters);
    params['issuer'] = 'org.rogue.impostor';
    return uri.replace(queryParameters: params).toString();
  }

  static String createTamperedTimestampEnvelope() {
    final valid = createAuthenticEnvelope();
    final uri = Uri.parse(valid);
    final params = Map<String, String>.from(uri.queryParameters);
    params['created'] = DateTime.parse(params['created']!).add(const Duration(hours: 1)).toIso8601String();
    return uri.replace(queryParameters: params).toString();
  }

  static String createUnregisteredKeyEnvelope() {
    final unregisteredSeed = Uint8List.fromList(List.generate(32, (i) => (i * 47 + 13) % 256));
    final envelope = TrustQrEnvelope.sign(
      issuer: 'org.unregistered.corp',
      payload: 'https://unregistered.corp/auth',
      privateKey: CryptoPrivateKey(bytes: unregisteredSeed, algorithm: CryptoAlgorithm.ed25519, keyId: 'unregistered-key-xyz'),
    );
    return envelope.toUriString();
  }
}

